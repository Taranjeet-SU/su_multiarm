#!/usr/bin/env python3
"""Generate the backend and provider capability tables from code so the docs cannot drift.

Sources of truth:

* backends: ``su_multi_arm.backends.capabilities.MATRIX`` (status per adapter and capability);
* chat providers: ``su_multi_arm.providers.capabilities.REGISTRY`` (first-match model patterns);
* embedding providers: the ``provider`` literal of ``su_multi_arm.core.config.EmbedderRole``.

Evidence levels are derived from the test tree: a backend counts as *real-service conformance* only
when its conformance test file exists and is marked ``external`` (those tests run against throwaway
containers; see ``docs/VALIDATION.md`` for the recorded runs). Provider evidence is fixed text that
states the repository's policy (no paid provider call has been made).

Usage::

    python scripts/gen_capability_tables.py          # rewrite docs/backends.md, docs/providers.md, README tables
    python scripts/gen_capability_tables.py --check  # exit 1 when any generated file is out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import get_args

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from su_multi_arm.backends.capabilities import CAPABILITIES, MATRIX  # noqa: E402
from su_multi_arm.core.config import EmbedderRole  # noqa: E402
from su_multi_arm.providers.capabilities import REGISTRY  # noqa: E402

GENERATED = "<!-- generated by scripts/gen_capability_tables.py; do not edit by hand -->"

# Where each backend kind's conformance evidence lives. A kind whose file is missing, or not marked
# ``external`` when it needs a service, makes the script fail instead of printing a stale claim.
BACKEND_TESTS: dict[str, str] = {
    "memory": "tests/conformance/test_backend_conformance.py",
    "sqlite": "tests/conformance/test_backend_conformance.py",
    "postgres": "tests/conformance/test_postgres_conformance.py",
    "sqlalchemy": "tests/conformance/test_sql_conformance.py",
    "opensearch": "tests/services/test_opensearch_adapter.py",
    "elasticsearch": "tests/conformance/test_elasticsearch_conformance.py",
    "neo4j": "tests/conformance/test_neo4j_conformance.py",
    "mongodb": "tests/conformance/test_mongodb_conformance.py",
}
IN_PROCESS = {"memory", "sqlite"}

CHAT_EVIDENCE: dict[str, str] = {
    "anthropic": "contract-mocked (mocked HTTP transport; no paid call made)",
    "openai": "contract-mocked (mocked HTTP transport; no paid call made)",
    "openai_compatible": "contract-mocked; optional `external` smoke against a local server you run",
    "none": "in-process (answer generation disabled)",
}
EMBEDDING_EVIDENCE: dict[str, str] = {
    "hash": "in-process, offline demo vectors (not semantic)",
    "sentence_transformers": "local model via optional extra; used (v1 runtime) in the 2026-10-12 diagnostics",
    "openai": "contract-mocked (no paid call made)",
    "openai_compatible": "contract-mocked",
}

STATUS_CELL = {"contracts": "yes", "legacy": "legacy", "planned": "planned"}


def _backend_evidence(kind: str) -> str:
    rel = BACKEND_TESTS.get(kind)
    if rel is None:
        raise SystemExit(f"no evidence mapping for backend kind {kind!r}; add it to BACKEND_TESTS")
    path = ROOT / rel
    if not path.exists():
        raise SystemExit(f"evidence file for {kind!r} is missing: {rel}")
    if kind in IN_PROCESS:
        return f"in-process conformance kit, default test run (`{rel}`)"
    if "pytest.mark.external" not in path.read_text():
        raise SystemExit(f"{rel} is not marked external; cannot claim real-service conformance for {kind!r}")
    return f"real-service conformance suite `{rel}` (passed in the 2.0.0a1 release run, see VALIDATION.md)"


def backends_table() -> str:
    header = "| Backend | " + " | ".join(CAPABILITIES) + " | Evidence |"
    rule = "|---|" + "---|" * len(CAPABILITIES) + "---|"
    rows = [header, rule]
    for kind, item in MATRIX.items():
        cells = []
        for capability in CAPABILITIES:
            status = item.status_of(capability)
            cells.append("—" if status is None else STATUS_CELL[status])
        rows.append(f"| `{kind}` | " + " | ".join(cells) + f" | {_backend_evidence(kind)} |")
    return "\n".join(rows)


def backend_notes() -> str:
    return "\n".join(f"- **`{kind}`**: {item.notes}" for kind, item in MATRIX.items())


def chat_table() -> str:
    rows = [
        "| Provider | Model pattern (first match wins) | Native structured output | Prompt caching | Streaming | Evidence |",
        "|---|---|---|---|---|---|",
    ]
    for cap in REGISTRY:
        native = cap.native_kind if cap.native_structured_output else ("role-declared" if cap.role_declared else "no")
        rows.append(
            f"| `{cap.provider}` | `{cap.pattern}` | {native} | {cap.prompt_caching} | "
            f"{'yes' if cap.streaming else 'no'} | {CHAT_EVIDENCE[cap.provider]} |"
        )
    rows.append(f"| `none` | — | — | — | — | {CHAT_EVIDENCE['none']} |")
    return "\n".join(rows)


def chat_summary_table() -> str:
    rows = ["| Chat provider | Model patterns | Evidence |", "|---|---|---|"]
    providers: dict[str, list[str]] = {}
    for cap in REGISTRY:
        providers.setdefault(cap.provider, []).append(cap.pattern)
    for provider, patterns in providers.items():
        rows.append(f"| `{provider}` | {len(patterns)} | {CHAT_EVIDENCE[provider]} |")
    rows.append(f"| `none` | — | {CHAT_EVIDENCE['none']} |")
    return "\n".join(rows)


def embedding_table() -> str:
    rows = ["| Embedding provider | Evidence |", "|---|---|"]
    for name in get_args(EmbedderRole.model_fields["provider"].annotation):
        rows.append(f"| `{name}` | {EMBEDDING_EVIDENCE[name]} |")
    return "\n".join(rows)


LEGEND = (
    "`yes` = implemented on the frozen contracts; `planned` = declared, no code, configuration naming it is "
    "rejected; `legacy` = v1 code only; `—` = not declared."
)


def backends_page() -> str:
    return f"""# Backends

{GENERATED}

Capability matrix from `su_multi_arm/backends/capabilities.py`. Configuration validation uses the
same matrix: an arm or storage slot that names a backend which does not serve the capability is a
`ConfigError`, never a silent fallback. {LEGEND}

{backends_table()}

"Real-service conformance" means the backend's conformance suite exists, is marked `external`, and
runs against a throwaway container (`tests/services/docker-compose.yml`). The recorded runs, image
versions and their limits are in [Validation](VALIDATION.md). It is not a relevance or scale result.

## Adapter notes

{backend_notes()}

Choosing a backend per projection (catalog, lexical, vector, records, graph, communities) is
described in [Configuration](CONFIGURATION.md#selecting-a-backend-per-projection).
"""


def providers_page() -> str:
    return f"""# Providers

{GENERATED}

Chat capabilities come from `su_multi_arm/providers/capabilities.py::REGISTRY`; configuration
validation accepts `structured_output: native` or `prompt_caching: controlled` only for declared
`(provider, model)` pairs. Hosted providers are **contract-mocked** in this repository: their entries
follow the providers' published API documentation and no paid call has been made.

## Chat providers

{chat_table()}

## Embedding providers

{embedding_table()}

Roles (`planner`, `reviewer`, `extractor`, `generator`, `community`, `judge`, `cache_gate`,
`embedder`, `reranker`) are configured separately; see
[Configuration](CONFIGURATION.md#model-providers-and-the-capability-registry).
"""


def readme_block() -> str:
    return f"""{GENERATED}

{backends_table()}

{LEGEND}

{chat_summary_table()}

{embedding_table()}"""


README_BEGIN = "<!-- BEGIN capability-tables -->"
README_END = "<!-- END capability-tables -->"


def render_readme(text: str) -> str:
    pattern = re.compile(re.escape(README_BEGIN) + r".*?" + re.escape(README_END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"README.md lacks the {README_BEGIN} / {README_END} markers")
    return pattern.sub(lambda _m: f"{README_BEGIN}\n{readme_block()}\n{README_END}", text)


def outputs() -> dict[Path, str]:
    readme = ROOT / "README.md"
    return {
        ROOT / "docs" / "backends.md": backends_page(),
        ROOT / "docs" / "providers.md": providers_page(),
        readme: render_readme(readme.read_text()),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated file is out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, content in outputs().items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date (run python scripts/gen_capability_tables.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
